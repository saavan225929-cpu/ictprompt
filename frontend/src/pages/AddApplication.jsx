import React, { useState } from 'react';
import { useNavigate, Link } from 'react-router-dom';
import { createApplication, extractErrorMessage } from '../api/applicationApi';
import { getTodayDateString } from '../utils/formatters';

const AddApplication = () => {
  const navigate = useNavigate();

  // Initial form values
  const [formData, setFormData] = useState({
    companyName: '',
    jobRole: '',
    jobType: 'Full-time',
    appliedDate: getTodayDateString(),
    expectedSalary: '',
    notes: ''
  });

  const [fieldErrors, setFieldErrors] = useState({});
  const [serverError, setServerError] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  // Field change handler
  const handleChange = (e) => {
    const { name, value } = e.target;
    setFormData((prev) => ({ ...prev, [name]: value }));

    // Clear field-specific error as user types
    if (fieldErrors[name]) {
      setFieldErrors((prev) => ({ ...prev, [name]: '' }));
    }
    if (serverError) {
      setServerError('');
    }
  };

  // Client-side validation
  const validateForm = () => {
    const errors = {};
    const todayStr = getTodayDateString();

    if (!formData.companyName.trim()) {
      errors.companyName = 'Company name is required';
    }

    if (!formData.jobRole.trim()) {
      errors.jobRole = 'Job role is required';
    }

    if (!formData.jobType) {
      errors.jobType = 'Job type is required';
    }

    if (!formData.appliedDate) {
      errors.appliedDate = 'Applied date is required';
    } else if (formData.appliedDate > todayStr) {
      errors.appliedDate = 'Applied date cannot be in the future';
    }

    setFieldErrors(errors);
    return Object.keys(errors).length === 0;
  };

  // Submission handler
  const handleSubmit = async (e) => {
    e.preventDefault();
    setServerError('');

    if (!validateForm()) {
      return;
    }

    try {
      setIsSubmitting(true);
      const res = await createApplication({
        companyName: formData.companyName.trim(),
        jobRole: formData.jobRole.trim(),
        jobType: formData.jobType,
        appliedDate: formData.appliedDate,
        expectedSalary: formData.expectedSalary.trim(),
        notes: formData.notes.trim()
      });

      if (res.success) {
        navigate('/', {
          state: { message: `Application ${res.data.applicationId} created successfully!` }
        });
      }
    } catch (err) {
      const errorMessage = extractErrorMessage(err);
      setServerError(errorMessage);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="form-page">
      <div className="form-card">
        <div className="form-header">
          <Link to="/" className="back-link">
            ← Back to Applications
          </Link>
          <h2 className="form-title">Add New Job Application</h2>
          <p className="form-subtitle">
            Initial status will be automatically set to <span className="highlight-tag">Applied</span>.
            Application ID and Follow-up Date will be generated by the server.
          </p>
        </div>

        {serverError && (
          <div className="alert-box alert-error">
            <span className="alert-icon">⚠️</span>
            <div className="alert-text">
              <strong>Submission Failed:</strong> {serverError}
            </div>
          </div>
        )}

        <form onSubmit={handleSubmit} noValidate>
          {/* Company Name */}
          <div className="form-group">
            <label htmlFor="companyName" className="form-label required">
              Company Name
            </label>
            <input
              type="text"
              id="companyName"
              name="companyName"
              className={`form-input ${fieldErrors.companyName ? 'input-error' : ''}`}
              placeholder="e.g. Google, Microsoft, Infosys"
              value={formData.companyName}
              onChange={handleChange}
              disabled={isSubmitting}
            />
            {fieldErrors.companyName && (
              <span className="field-error-text">{fieldErrors.companyName}</span>
            )}
          </div>

          {/* Job Role */}
          <div className="form-group">
            <label htmlFor="jobRole" className="form-label required">
              Job Role
            </label>
            <input
              type="text"
              id="jobRole"
              name="jobRole"
              className={`form-input ${fieldErrors.jobRole ? 'input-error' : ''}`}
              placeholder="e.g. Software Engineer, Frontend Developer"
              value={formData.jobRole}
              onChange={handleChange}
              disabled={isSubmitting}
            />
            {fieldErrors.jobRole && (
              <span className="field-error-text">{fieldErrors.jobRole}</span>
            )}
          </div>

          {/* Grid row: Job Type & Applied Date */}
          <div className="form-row">
            <div className="form-group col-half">
              <label htmlFor="jobType" className="form-label required">
                Job Type
              </label>
              <select
                id="jobType"
                name="jobType"
                className={`form-select ${fieldErrors.jobType ? 'input-error' : ''}`}
                value={formData.jobType}
                onChange={handleChange}
                disabled={isSubmitting}
              >
                <option value="Full-time">Full-time</option>
                <option value="Internship">Internship</option>
                <option value="Contract">Contract</option>
              </select>
              {fieldErrors.jobType && (
                <span className="field-error-text">{fieldErrors.jobType}</span>
              )}
            </div>

            <div className="form-group col-half">
              <label htmlFor="appliedDate" className="form-label required">
                Applied Date
              </label>
              <input
                type="date"
                id="appliedDate"
                name="appliedDate"
                max={getTodayDateString()}
                className={`form-input ${fieldErrors.appliedDate ? 'input-error' : ''}`}
                value={formData.appliedDate}
                onChange={handleChange}
                disabled={isSubmitting}
              />
              <span className="field-help-text">Cannot be in the future.</span>
              {fieldErrors.appliedDate && (
                <span className="field-error-text">{fieldErrors.appliedDate}</span>
              )}
            </div>
          </div>

          {/* Expected Salary */}
          <div className="form-group">
            <label htmlFor="expectedSalary" className="form-label">
              Expected Salary <span className="optional-tag">(Optional)</span>
            </label>
            <input
              type="text"
              id="expectedSalary"
              name="expectedSalary"
              className="form-input"
              placeholder="e.g. $85,000 / yr, 8 LPA, or $45 / hr"
              value={formData.expectedSalary}
              onChange={handleChange}
              disabled={isSubmitting}
            />
          </div>

          {/* Notes */}
          <div className="form-group">
            <label htmlFor="notes" className="form-label">
              Notes <span className="optional-tag">(Optional)</span>
            </label>
            <textarea
              id="notes"
              name="notes"
              rows={4}
              className="form-textarea"
              placeholder="Add interview contacts, referral details, portal links, or preparation notes..."
              value={formData.notes}
              onChange={handleChange}
              disabled={isSubmitting}
            />
          </div>

          {/* Form Actions */}
          <div className="form-actions">
            <button
              type="button"
              className="btn btn-secondary"
              onClick={() => navigate('/')}
              disabled={isSubmitting}
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn btn-primary"
              disabled={isSubmitting}
            >
              {isSubmitting ? 'Creating Application...' : 'Create Application'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};

export default AddApplication;
